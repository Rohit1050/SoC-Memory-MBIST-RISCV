#!/usr/bin/env python3
"""
ihex2vhx.py  —  Convert Intel HEX to Verilog $readmemh hex (.vhx)

Usage:
    python3 ihex2vhx.py <input.hex> <output.vhx> [--base 0x00040000] [--words 4096]

The output is a plain word-addressed Verilog hex file:
  • One 32-bit word per line (little-endian byte assembly)
  • @<address> markers inserted whenever the word address is non-contiguous
  • Compatible with $readmemh in tb_soc_top.sv

Default base address : 0x00040000  (ICCM base)
Default word count   : 4096        (16 KB ICCM = 4096 × 4-byte words)

For DCCM use:  --base 0x00082000 --words 2048
"""

import argparse
import sys

def parse_ihex(path):
    """Parse Intel HEX file → dict{byte_address: byte_value}."""
    byte_map = {}
    segment_base = 0  # from record type 02 (extended segment) or 04 (extended linear)

    with open(path, 'r') as f:
        for lineno, raw in enumerate(f, 1):
            line = raw.strip()
            if not line:
                continue
            if line[0] != ':':
                raise ValueError(f"Line {lineno}: expected ':', got '{line[0]}'")

            byte_count  = int(line[1:3],   16)
            address     = int(line[3:7],   16)
            record_type = int(line[7:9],   16)
            data_hex    = line[9:9 + byte_count * 2]
            checksum    = int(line[9 + byte_count * 2 : 11 + byte_count * 2], 16)

            # Verify checksum
            all_bytes = [int(line[i:i+2], 16) for i in range(1, 9 + byte_count * 2, 2)]
            calc = (256 - (sum(all_bytes) & 0xFF)) & 0xFF
            if calc != checksum:
                raise ValueError(f"Line {lineno}: checksum mismatch (got {checksum:#04x}, expected {calc:#04x})")

            if record_type == 0x00:   # Data
                abs_addr = segment_base + address
                data_bytes = bytes.fromhex(data_hex)
                for i, b in enumerate(data_bytes):
                    byte_map[abs_addr + i] = b

            elif record_type == 0x01: # End-of-file
                break

            elif record_type == 0x02: # Extended segment address (×16)
                segment_base = int(data_hex, 16) << 4

            elif record_type == 0x04: # Extended linear address (upper 16 bits)
                segment_base = int(data_hex, 16) << 16

            elif record_type == 0x03: # Start segment address — ignore
                pass
            elif record_type == 0x05: # Start linear address — ignore
                pass
            else:
                print(f"[WARN] Line {lineno}: unknown record type {record_type:#04x}, skipping")

    return byte_map


def write_vhx(byte_map, out_path, base_addr, num_words):
    """Write Verilog $readmemh file from byte_map."""
    prev_word_addr = None

    with open(out_path, 'w') as f:
        f.write(f"// Verilog hex dump — base 0x{base_addr:08X}, {num_words} words\n")
        f.write(f"// Generated by ihex2vhx.py\n")

        for w in range(num_words):
            byte_addr = base_addr + w * 4
            # Assemble 4 bytes little-endian
            b0 = byte_map.get(byte_addr + 0, 0)
            b1 = byte_map.get(byte_addr + 1, 0)
            b2 = byte_map.get(byte_addr + 2, 0)
            b3 = byte_map.get(byte_addr + 3, 0)
            word = (b3 << 24) | (b2 << 16) | (b1 << 8) | b0

            # Emit @address marker on first word or after a gap
            if prev_word_addr is None or w != prev_word_addr + 1:
                f.write(f"@{w:08X}\n")
            prev_word_addr = w

            f.write(f"{word:08x}\n")

    print(f"[OK] Written {num_words} words to '{out_path}'")


def main():
    ap = argparse.ArgumentParser(description="Convert Intel HEX to Verilog $readmemh hex")
    ap.add_argument("input",  help="Input Intel HEX file (.hex)")
    ap.add_argument("output", help="Output Verilog hex file (.vhx)")
    ap.add_argument("--base",  default="0x00040000",
                    help="Base byte-address of the memory (default: 0x00040000 = ICCM)")
    ap.add_argument("--words", default=4096, type=int,
                    help="Number of 32-bit words to emit (default: 4096 = 16 KB)")
    args = ap.parse_args()

    base = int(args.base, 0)

    print(f"[INFO] Reading  : {args.input}")
    print(f"[INFO] Base addr: 0x{base:08X}")
    print(f"[INFO] Words    : {args.words} ({args.words * 4 // 1024} KB)")

    byte_map = parse_ihex(args.input)
    if not byte_map:
        print("[WARN] No data records found in input file!", file=sys.stderr)

    # Sanity: how many bytes landed inside our target window?
    in_window = sum(1 for a in byte_map if base <= a < base + args.words * 4)
    out_window = sum(1 for a in byte_map if not (base <= a < base + args.words * 4))
    print(f"[INFO] Bytes in  window: {in_window}")
    if out_window:
        addrs = [a for a in byte_map if not (base <= a < base + args.words * 4)]
        lo, hi = min(addrs), max(addrs)
        print(f"[WARN] Bytes out of window: {out_window}  (range 0x{lo:08X}–0x{hi:08X})")
        print(f"[WARN] These are likely .data initializers loaded into ICCM for DCCM copy — normal for bare-metal firmware.")

    write_vhx(byte_map, args.output, base, args.words)


if __name__ == "__main__":
    main()
